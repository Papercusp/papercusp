import { test } from 'vitest';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const harnessDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'harness');
const promptPath = join(harnessDir, 'blueprints', 'base', 'prompts', 'content-fixer.md');

test('content-fixer persona treats the dispatch extra as the sole authoritative offender list', () => {
  const prompt = readFileSync(promptPath, 'utf8');

  assert.match(prompt, /`--git-sync-content-error` extra[\s\S]*only authoritative offender list/);
  assert.match(prompt, /open \*\*git-sync-content-error escalation\*\*[\s\S]*human-visible status/);
  assert.match(prompt, /never use it as the offender list/);
  assert.doesNotMatch(
    prompt,
    /open \*\*git-sync-content-error escalation\*\*[\s\S]*authoritative `files\[\]` list/,
  );
});

test('content-fixer persona repairs generated docs at their canonical source', () => {
  const prompt = readFileSync(promptPath, 'utf8');
  const classify = prompt.indexOf('classify it before editing it');
  const open = prompt.indexOf('open it at its full path');

  assert.ok(classify >= 0, 'generated-file classification must be explicit');
  assert.ok(open > classify, 'classification must happen before a file is opened for editing');
  assert.match(prompt, /apps\/operator-docs\/src\/content\/docs\//);
  assert.match(prompt, /⚠ GENERATED PROJECTION — DO NOT EDIT THIS FILE BY HAND/);
  assert.match(prompt, /Never hand-edit it/);
  assert.match(prompt, /docs:author \{ overwrite: true \}/);
  assert.match(prompt, /canonical document/);
  assert.match(prompt, /projection will be rewritten/);
  assert.match(prompt, /Never alter a generated-projection header/);
});
